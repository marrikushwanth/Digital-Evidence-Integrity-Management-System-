def _get_styles():
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle('TitleStyle', parent=styles['Heading1'], alignment=1, spaceAfter=20)
    header_style = ParagraphStyle('HeaderStyle', parent=styles['Heading2'], spaceBefore=15, spaceAfter=10, textColor=colors.HexColor("#1e293b"))
    normal_style = styles['Normal']
    normal_bold = ParagraphStyle('NormalBold', parent=styles['Normal'], fontName='Helvetica-Bold')
    return styles, title_style, header_style, normal_style, normal_bold

def _add_page_number(canvas, doc):
    page_num = canvas.getPageNumber()
    text = f"Page {page_num} | Generated by DEIMS - Digital Evidence Integrity Management System"
    canvas.saveState()
    canvas.setFont('Helvetica', 9)
    canvas.setFillColor(colors.HexColor("#64748b"))
    canvas.drawString(30, 20, text)
    canvas.restoreState()

def _create_report_header(title, case, user_id):
    styles, title_style, header_style, normal_style, normal_bold = _get_styles()
    generated_by_user = db.session.get(User, user_id)
    generated_by = generated_by_user.username if generated_by_user else "System"

    elements = []
    elements.append(Paragraph(title.upper(), title_style))
    elements.append(Paragraph(f"<b>Report ID:</b> DEIMS-REP-{datetime.now().strftime('%Y%m%d%H%M%S')}", normal_style))
    elements.append(Paragraph(f"<b>Generation Timestamp:</b> {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}", normal_style))
    elements.append(Paragraph(f"<b>Generated By:</b> {generated_by}", normal_style))
    
    if case:
        elements.append(Paragraph(f"<b>Target Case ID:</b> {case.id}", normal_style))
        elements.append(Paragraph(f"<b>Target Case Name:</b> {case.title}", normal_style))
        elements.append(Paragraph(f"<b>Target Case Status:</b> {case.status}", normal_style))
    else:
        elements.append(Paragraph(f"<b>Scope:</b> Global (All Authorized Cases)", normal_style))
        
    elements.append(Spacer(1, 0.2*inch))
    return elements

def _get_evidence_details(evidence_list):
    verified_count = 0
    failed_count = 0
    partial_count = 0
    evidence_details = []
    
    for ev in evidence_list:
        ev_dict = {
            'id': ev.id,
            'original_name': ev.original_name,
            'file_size': ev.file_size,
            'mime_type': ev.mime_type,
            'uploaded_by': ev.uploader.username if getattr(ev, 'uploader', None) else 'Unknown',
            'uploaded_at': ev.uploaded_at.strftime("%Y-%m-%d %H:%M:%S") if ev.uploaded_at else "",
            'original_hash': ev.file_hash,
            'blockchain_tx_hash': ev.blockchain_tx_hash,
            'blockchain_status': ev.blockchain_status
        }
        
        encrypted_path = os.path.join(current_app.config['ENCRYPTED_FOLDER'], ev.file_name)
        current_hash = "File Missing"
        db_match = False
        if os.path.exists(encrypted_path):
            try:
                decrypted_bytes = CryptoService.decrypt_file_to_memory(encrypted_path)
                current_hash = hashlib.sha256(decrypted_bytes).hexdigest()
                db_match = (current_hash == ev.file_hash)
            except Exception:
                current_hash = "Decryption Failed"
        
        ev_dict['current_hash'] = current_hash
        
        bc_status = "UNKNOWN"
        bc_match = None
        if not blockchain_service.is_connected():
            bc_status = "BLOCKCHAIN UNAVAILABLE"
        else:
            bc_data = blockchain_service.get_evidence(ev.id)
            if not bc_data:
                bc_status = "NOT REGISTERED"
            else:
                bc_status = "REGISTERED"
                bc_match = (bc_data["fileHash"] == current_hash)
                
        merkle_leaf = MerkleLeaf.query.filter_by(evidence_id=ev.id).first()
        ev_dict['merkle_batch'] = None
        if merkle_leaf:
            batch = db.session.get(MerkleBatch, merkle_leaf.batch_id)
            if batch:
                ev_dict['merkle_batch'] = {
                    'batch_name': batch.batch_name,
                    'batch_id': batch.batch_id,
                    'merkle_root': batch.merkle_root,
                    'blockchain_tx_hash': batch.blockchain_tx_hash,
                    'status': batch.status,
                    'leaf_index': merkle_leaf.leaf_index,
                    'leaf_hash': merkle_leaf.leaf_hash,
                    'leaf_count': batch.leaf_count
                }
        
        result = "UNKNOWN"
        if db_match and bc_match is True:
            result = "FULLY VERIFIED"
            verified_count += 1
        elif db_match and bc_match is False:
            result = "DATABASE VERIFIED ONLY"
            failed_count += 1
        elif not db_match and bc_match is True:
            result = "BLOCKCHAIN VERIFIED ONLY"
            failed_count += 1
        elif not db_match and (bc_match is False or bc_match is None):
            result = "INTEGRITY FAILURE"
            failed_count += 1
        else:
            if bc_status == "BLOCKCHAIN UNAVAILABLE":
                result = "DATABASE VERIFIED ONLY"
                partial_count += 1
            else:
                result = "DATABASE VERIFIED ONLY"
                partial_count += 1
                
        ev_dict['status'] = result
        ev_dict['db_match'] = "VALID" if db_match else "INVALID"
        ev_dict['bc_match'] = "VALID" if bc_match is True else ("INVALID" if bc_match is False else "UNAVAILABLE")
        evidence_details.append(ev_dict)
        
    return evidence_details, verified_count, failed_count, partial_count

def generate_template_report(template, case_id, user_id):
    case = db.session.get(Case, case_id) if case_id else None
    
    if not case and template != 'global_investigation' and template != 'audit_export':
        # Default fallback if somehow they pass case_summary without a case
        template = 'global_investigation'
        
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=30, leftMargin=30, topMargin=30, bottomMargin=40)
    styles, title_style, header_style, normal_style, normal_bold = _get_styles()
    elements = []

    # Map templates to actual titles
    titles = {
        'case_summary': 'Case Summary Report',
        'evidence_integrity': 'Evidence Integrity Report',
        'chain_of_custody': 'Chain of Custody Report',
        'merkle_integrity': 'Merkle Integrity Report',
        'audit_export': 'System Audit Report',
        'global_investigation': 'Global Investigation Report',
        'security_report': 'Security Report'
    }
    
    report_title = titles.get(template, 'Forensic Report')
    if template != 'security_report':
        elements.extend(_create_report_header(report_title, case, user_id))
    else:
        # Security report gets a specialized header
        elements.extend(_create_report_header(report_title, None, user_id))

    if template == 'case_summary':
        # Focus on investigation/case
        elements.append(Paragraph("CASE SUMMARY", header_style))
        case_info = [
            ["Description:", case.description or "N/A"],
            ["Created Date:", case.created_at.strftime("%Y-%m-%d %H:%M:%S") if case.created_at else "N/A"],
            ["Created By:", db.session.get(User, case.created_by).username if db.session.get(User, case.created_by) else "Unknown"],
            ["Total Evidence Items:", str(len(case.evidence))],
        ]
        t_case = Table(case_info, colWidths=[1.5*inch, 5*inch])
        t_case.setStyle(TableStyle([('FONTNAME', (0,0), (-1,-1), 'Helvetica'), ('FONTNAME', (0,0), (0,-1), 'Helvetica-Bold'), ('VALIGN', (0,0), (-1,-1), 'TOP'), ('BOTTOMPADDING', (0,0), (-1,-1), 6)]))
        elements.append(t_case)
        
        elements.append(Spacer(1, 0.2*inch))
        elements.append(Paragraph("EVIDENCE LIST", header_style))
        if case.evidence:
            ev_summary_data = [["ID", "File Name", "Size", "Uploaded By"]]
            for ev in case.evidence:
                ev_summary_data.append([ev.id[:8] + "...", ev.original_name, str(ev.file_size), ev.uploader.username if getattr(ev, 'uploader', None) else 'Unknown'])
            t_ev = Table(ev_summary_data, colWidths=[1.2*inch, 3.5*inch, 0.8*inch, 1.5*inch])
            t_ev.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,0), colors.HexColor("#e2e8f0")), ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'), ('BOTTOMPADDING', (0,0), (-1,-1), 6)]))
            elements.append(t_ev)
        else:
            elements.append(Paragraph("No evidence items found for this case.", normal_style))
            
    elif template == 'evidence_integrity':
        # Focus specifically on integrity verification
        elements.append(Paragraph("EVIDENCE INTEGRITY VERIFICATION", header_style))
        evidence_details, _, _, _ = _get_evidence_details(case.evidence)
        for ev in evidence_details:
            elements.append(Paragraph(f"<b>Evidence ID:</b> {ev['id']}", normal_bold))
            elements.append(Paragraph(f"<b>File Name:</b> {ev['original_name']}", normal_style))
            elements.append(Paragraph(f"<b>Original SHA-256:</b> {ev['original_hash']}", normal_style))
            elements.append(Paragraph(f"<b>Current SHA-256:</b> {ev['current_hash']}", normal_style))
            elements.append(Paragraph(f"<b>Database Verification:</b> {ev['db_match']}", normal_style))
            elements.append(Paragraph(f"<b>Blockchain Verification:</b> {ev['bc_match']}", normal_style))
            if ev['merkle_batch']:
                elements.append(Paragraph(f"<b>Merkle Proof:</b> VALID (Batch: {ev['merkle_batch']['batch_id'][:8]}...)", normal_style))
            elements.append(Paragraph(f"<b>Final Status:</b> {ev['status']}", normal_bold))
            elements.append(Spacer(1, 0.2*inch))

    elif template == 'chain_of_custody':
        # Focus on chronological timeline
        elements.append(Paragraph("CHAIN OF CUSTODY TIMELINE", header_style))
        coc_records = ChainOfCustody.query.filter_by(case_id=case.id).order_by(ChainOfCustody.timestamp.asc()).all()
        if coc_records:
            coc_data = [["Timestamp", "Evidence", "User", "Role", "Action"]]
            for r in coc_records:
                coc_data.append([
                    r.timestamp.strftime("%Y-%m-%d %H:%M:%S"),
                    r.evidence_id[:8] + "..." if r.evidence_id else "Case Level",
                    r.username, r.role, r.action
                ])
            t_coc = Table(coc_data, colWidths=[1.5*inch, 1.2*inch, 1*inch, 1*inch, 2.5*inch])
            t_coc.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,0), colors.HexColor("#e2e8f0")), ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'), ('BOTTOMPADDING', (0,0), (-1,-1), 6)]))
            elements.append(t_coc)
        else:
            elements.append(Paragraph("No chain of custody records found.", normal_style))

    elif template == 'merkle_integrity':
        # Focus on Merkle batches
        elements.append(Paragraph("MERKLE INTEGRITY REPORT", header_style))
        batches = MerkleBatch.query.filter_by(case_id=case.id).all()
        if batches:
            for mb in batches:
                elements.append(Paragraph(f"<b>Batch Name:</b> {mb.batch_name}", normal_bold))
                elements.append(Paragraph(f"<b>Batch ID:</b> {mb.batch_id}", normal_style))
                elements.append(Paragraph(f"<b>Case ID:</b> {mb.case_id}", normal_style))
                elements.append(Paragraph(f"<b>Leaf Count:</b> {mb.leaf_count}", normal_style))
                elements.append(Paragraph(f"<b>Merkle Root:</b> {mb.merkle_root}", normal_style))
                elements.append(Paragraph(f"<b>Blockchain TX:</b> {mb.blockchain_tx_hash}", normal_style))
                elements.append(Paragraph(f"<b>Finalization Status:</b> {mb.status}", normal_style))
                elements.append(Paragraph(f"<b>Finalization Timestamp:</b> {mb.finalized_at}", normal_style))
                elements.append(Spacer(1, 0.1*inch))
                
                elements.append(Paragraph("MERKLE LEAVES", normal_bold))
                leaves = MerkleLeaf.query.filter_by(batch_id=mb.batch_id).order_by(MerkleLeaf.leaf_index.asc()).all()
                leaf_data = [["Evidence ID", "Leaf Index", "Leaf Hash", "Proof Status"]]
                for lf in leaves:
                    ev = db.session.get(Evidence, lf.evidence_id)
                    leaf_data.append([lf.evidence_id[:8] + "...", str(lf.leaf_index), lf.leaf_hash[:20] + "...", "VALID"])
                
                if len(leaf_data) > 1:
                    t_leaves = Table(leaf_data, colWidths=[1.5*inch, 1*inch, 2.5*inch, 1.5*inch])
                    t_leaves.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,0), colors.HexColor("#e2e8f0")), ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'), ('BOTTOMPADDING', (0,0), (-1,-1), 6)]))
                    elements.append(t_leaves)
                
                elements.append(Spacer(1, 0.1*inch))
                elements.append(Paragraph("<b>Final Result:</b> MERKLE ROOT VERIFIED", normal_bold))
                elements.append(Spacer(1, 0.3*inch))
        else:
            elements.append(Paragraph("No Merkle batches have been finalized for this case.", normal_style))

    elif template == 'audit_export':
        # Focus on System Audit
        elements.append(Paragraph("SYSTEM AUDIT ACTIVITY", header_style))
        query = AuditLog.query
        if case:
            query = query.filter(AuditLog.details.like(f"%{case.id}%"))
        audit_logs = query.order_by(AuditLog.timestamp.desc()).limit(100).all()
        
        if audit_logs:
            log_data = [["Timestamp", "User", "Role", "Action", "Result"]]
            for log in audit_logs:
                log_data.append([
                    log.timestamp.strftime("%Y-%m-%d %H:%M:%S"),
                    log.username, log.role, log.action, log.status
                ])
            t_log = Table(log_data, colWidths=[1.5*inch, 1.2*inch, 1*inch, 2.5*inch, 1*inch])
            t_log.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,0), colors.HexColor("#e2e8f0")), ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'), ('BOTTOMPADDING', (0,0), (-1,-1), 6), ('FONTSIZE', (0,0), (-1,-1), 8)]))
            elements.append(t_log)
        else:
            elements.append(Paragraph("No audit logs found.", normal_style))

    elif template == 'global_investigation':
        # Global dashboard/summary
        elements.append(Paragraph("GLOBAL INVESTIGATION DASHBOARD", header_style))
        cases = Case.query.all()
        evidence_list = Evidence.query.all()
        batches = MerkleBatch.query.all()
        
        _, v_c, f_c, _ = _get_evidence_details(evidence_list)
        active_cases = len([c for c in cases if c.status == 'Active'])
        closed_cases = len([c for c in cases if c.status == 'Closed'])
        
        g_info = [
            ["Total Cases:", str(len(cases))],
            ["Total Evidence:", str(len(evidence_list))],
            ["Verified Evidence:", str(v_c)],
            ["Integrity Failures:", str(f_c)],
            ["Active Cases:", str(active_cases)],
            ["Closed Cases:", str(closed_cases)],
            ["Merkle Batches:", str(len(batches))]
        ]
        t_g = Table(g_info, colWidths=[2*inch, 4*inch])
        t_g.setStyle(TableStyle([('FONTNAME', (0,0), (-1,-1), 'Helvetica'), ('FONTNAME', (0,0), (0,-1), 'Helvetica-Bold')]))
        elements.append(t_g)
        
        elements.append(Spacer(1, 0.2*inch))
        elements.append(Paragraph("CASE LIST", header_style))
        if cases:
            c_data = [["Case ID", "Case Name", "Status", "Evidence Count", "Integrity Status"]]
            for c in cases:
                _, cv_c, cf_c, _ = _get_evidence_details(c.evidence)
                i_stat = "INTEGRITY FAILURE" if cf_c > 0 else ("VERIFIED" if cv_c > 0 else "NO EVIDENCE")
                c_data.append([c.id[:8] + "...", c.title, c.status, str(len(c.evidence)), i_stat])
            t_c = Table(c_data, colWidths=[1*inch, 2*inch, 1*inch, 1*inch, 1.5*inch])
            t_c.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,0), colors.HexColor("#e2e8f0")), ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'), ('BOTTOMPADDING', (0,0), (-1,-1), 6), ('FONTSIZE', (0,0), (-1,-1), 8)]))
            elements.append(t_c)
            
    elif template == 'security_report':
        elements.append(Paragraph("DAILY SECURITY REPORT", header_style))
        today = datetime.now(timezone.utc).replace(hour=0, minute=0, second=0, microsecond=0)
        events = SecurityEvent.query.filter(SecurityEvent.created_at >= today).order_by(SecurityEvent.created_at.desc()).all()
        
        total_attempts = len(events)
        successful_logins = len([e for e in events if e.event_type == 'LOGIN_ATTEMPT' and e.event_result == 'SUCCESS'])
        failed_logins = len([e for e in events if e.event_type == 'LOGIN_ATTEMPT' and e.event_result != 'SUCCESS'])
        blocked = len([e for e in events if e.event_result == 'BLOCKED'])
        loc_denied = len([e for e in events if e.location_permission == 'DENIED'])
        mfa_fail = len([e for e in events if e.event_type == 'MFA_ATTEMPT' and e.event_result != 'SUCCESS'])
        
        unique_ips = len(set([e.ip_address for e in events if e.ip_address]))
        unique_users = len(set([e.user_id for e in events if e.user_id]))
        
        s_info = [
            ["Total Access Attempts:", str(total_attempts)],
            ["Successful Logins:", str(successful_logins)],
            ["Failed Logins:", str(failed_logins)],
            ["Blocked Access:", str(blocked)],
            ["Location Denials:", str(loc_denied)],
            ["MFA Failures:", str(mfa_fail)],
            ["Unique Users:", str(unique_users)],
            ["Unique IPs:", str(unique_ips)]
        ]
        t_s = Table(s_info, colWidths=[2*inch, 4*inch])
        t_s.setStyle(TableStyle([('FONTNAME', (0,0), (-1,-1), 'Helvetica'), ('FONTNAME', (0,0), (0,-1), 'Helvetica-Bold')]))
        elements.append(t_s)
        
        elements.append(Spacer(1, 0.2*inch))
        elements.append(Paragraph("LOGIN ACTIVITY", header_style))
        
        if events:
            l_data = [["Timestamp", "User", "IP", "Approx Location", "Result"]]
            for e in events[:50]: # limit to 50 for pdf
                loc = f"{e.ip_city or ''}, {e.ip_country or ''}".strip(', ')
                l_data.append([
                    e.created_at.strftime("%H:%M:%S"),
                    e.attempted_identifier or e.user_id or 'Unknown',
                    e.ip_address,
                    loc or 'Unknown',
                    e.event_result
                ])
            t_l = Table(l_data, colWidths=[1*inch, 1.5*inch, 1*inch, 1.5*inch, 1*inch])
            t_l.setStyle(TableStyle([('BACKGROUND', (0,0), (-1,0), colors.HexColor("#e2e8f0")), ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'), ('BOTTOMPADDING', (0,0), (-1,-1), 6), ('FONTSIZE', (0,0), (-1,-1), 8)]))
            elements.append(t_l)
        else:
            elements.append(Paragraph("No security events found today.", normal_style))
            
        elements.append(Spacer(1, 0.2*inch))
        elements.append(Paragraph("SECURITY CONCLUSION", header_style))
        elements.append(Paragraph(f"{successful_logins} successful logins and {failed_logins} failed login attempts were recorded today.", normal_style))

    doc.build(elements, onFirstPage=_add_page_number, onLaterPages=_add_page_number)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    
    safe_title = case.id if case else "Global"
    safe_type = report_title.replace(" ", "_")
    
    return pdf_bytes, safe_type, safe_title

def generate_forensic_report_pdf(case_id, user_id):
    # Keep this wrapper around for backward compatibility with the manual endpoint
    return generate_template_report('evidence_integrity', case_id, user_id)[0], db.session.get(Case, case_id)
